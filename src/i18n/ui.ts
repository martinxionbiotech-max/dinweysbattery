// Shared UI dictionary for English (/), Arabic (/ar/) and Spanish (/es/) locales.
export type Locale = "en" | "ar" | "es";

export const locales: Locale[] = ["en", "ar", "es"];

/** Detect locale from a URL pathname. */
export function localeFromPath(pathname: string): Locale {
  if (pathname.startsWith("/ar/") || pathname === "/ar") return "ar";
  if (pathname.startsWith("/es/") || pathname === "/es") return "es";
  return "en";
}

/** Swap the locale prefix of a path. */
export function localizePath(pathname: string, locale: Locale): string {
  let base = pathname;
  if (base.startsWith("/ar/")) base = base.slice(3);
  else if (base.startsWith("/es/")) base = base.slice(3);
  if (locale === "en") return base.startsWith("/") ? base : "/" + base;
  return `/${locale}${base.startsWith("/") ? base : "/" + base}`;
}

